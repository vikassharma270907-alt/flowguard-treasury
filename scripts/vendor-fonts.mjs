/**
 * Vendors the exact Google Fonts woff2 subsets used by the IntentGate client
 * into client/public/fonts and regenerates client/src/fonts.css with
 * same-origin @font-face rules.
 *
 * Why: serving fonts from our own origin removes two third-party connections
 * and eliminates the post-load web-font swap re-layout that dominated
 * main-thread blocking time on throttled mobile devices.
 *
 * Run with: node scripts/vendor-fonts.mjs
 */
import fs from 'node:fs';
import path from 'node:path';

const CSS_URL =
  'https://fonts.googleapis.com/css2?family=Inter:wght@300;400;500;600;700' +
  '&family=Noto+Sans+Devanagari:wght@400;500;600;700' +
  '&family=JetBrains+Mono:wght@400;500&display=swap';

// Subsets that can appear in IntentGate content (English + Hindi UI).
const KEEP_SUBSETS = new Set(['latin', 'latin-ext', 'devanagari']);

// Google only serves woff2 URLs to modern browsers.
const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 ' +
  '(KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36';

const fontsDir = path.resolve('client/public/fonts');
fs.mkdirSync(fontsDir, { recursive: true });

const res = await fetch(CSS_URL, { headers: { 'user-agent': UA } });
if (!res.ok) throw new Error(`Google Fonts CSS request failed: ${res.status}`);
const css = await res.text();

const out = [
  '/* Self-hosted @font-face rules. Generated by scripts/vendor-fonts.mjs —',
  '   do not edit by hand. Subsets: latin, latin-ext, devanagari. */',
  ''
];

let downloaded = 0;
let faces = 0;

const blockRe = /\/\*\s*([a-z-]+)\s*\*\/\s*@font-face\s*\{([^}]+)\}/g;
for (const [, subset, body] of css.matchAll(blockRe)) {
  if (!KEEP_SUBSETS.has(subset)) continue;
  const family = /font-family:\s*'([^']+)'/.exec(body)?.[1];
  const weight = /font-weight:\s*(\d+)/.exec(body)?.[1];
  const url = /url\((https:[^)]+)\)/.exec(body)?.[1];
  const range = /unicode-range:\s*([^;]+);/.exec(body)?.[1];
  if (!family || !weight || !url || !range) continue;

  const slug = `${family.toLowerCase().replace(/[^a-z0-9]+/g, '-')}-${weight}-${subset}.woff2`;
  const dest = path.join(fontsDir, slug);
  if (!fs.existsSync(dest)) {
    const fontRes = await fetch(url);
    if (!fontRes.ok) throw new Error(`Font download failed: ${url} (${fontRes.status})`);
    const buf = Buffer.from(await fontRes.arrayBuffer());
    fs.writeFileSync(dest, buf);
    downloaded += 1;
    console.log(`  fetched ${slug} (${(buf.length / 1024).toFixed(1)} KB)`);
  }

  faces += 1;
  out.push(`/* ${subset} */`);
  out.push('@font-face {');
  out.push(`  font-family: '${family}';`);
  out.push('  font-style: normal;');
  out.push(`  font-weight: ${weight};`);
  out.push('  font-display: swap;');
  out.push(`  src: url(/fonts/${slug}) format('woff2');`);
  out.push(`  unicode-range: ${range};`);
  out.push('}');
  out.push('');
}

fs.writeFileSync(path.resolve('client/src/fonts.css'), out.join('\n'));
console.log(`✅ fonts.css written with ${faces} @font-face rules (${downloaded} files downloaded).`);
